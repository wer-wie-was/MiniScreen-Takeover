    static void draw(Canvas c,Paint p,String value,float left,float top,float maxWidth,float height){
        if(value.isEmpty()||maxWidth<=0||height<=0)return;
        float units=-1;for(int i=0;i<value.length();i++)units+=glyph(value.charAt(i))[0].length()+1;
        float sx=Math.min(height/10f,maxWidth/Math.max(1,units)),sy=height/7f;
        boolean aa=p.isAntiAlias();p.setAntiAlias(false);p.setStyle(Paint.Style.FILL);
        for(int i=0;i<value.length();i++){
            String[] rows=glyph(value.charAt(i));
            for(int y=0;y<7;y++)for(int x=0;x<rows[y].length();x++)if(rows[y].charAt(x)=='1')c.drawRect(left+x*sx,top+y*sy,left+(x+1)*sx,top+(y+1)*sy,p);
            left+=(rows[0].length()+1)*sx;
        }
        p.setAntiAlias(aa);
    }
